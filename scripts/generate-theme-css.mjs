/**
 * Generates src/styles/themes.css from src/lib/theme/palettes.json.
 *
 * palettes.json is the single source of truth for every aesthetic. This script
 * emits one `[data-theme="..."]` block per aesthetic so the server can pick the
 * theme by setting a single attribute on <html> — no JS, no flash of unthemed
 * content. Run `npm run theme:css` after editing palettes.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const palettes = JSON.parse(readFileSync('src/lib/theme/palettes.json', 'utf8'));

const DEFAULT = 'soft';
const DARK = new Set(['noir', 'cyberpunk', 'grunge', 'fantasy', 'vaporwave']);

/*
 * Tailwind reserves the --shadow-* namespace for shadow utilities, so emitting
 * a palette var of the same name would make `--shadow-soft: var(--shadow-soft)`
 * self-referential. Palette keys stay as-is for JS consumers (the MUI theme);
 * only the emitted CSS custom property is renamed.
 */
const CSS_KEY = {
  '--shadow-soft': '--elevation-soft',
  '--shadow-medium': '--elevation-medium',
};

const block = (selector, name) => {
  const vars = Object.entries(palettes[name])
    .map(([k, v]) => `  ${CSS_KEY[k] ?? k}: ${v};`)
    .join('\n');
  return `${selector} {\n${vars}\n  color-scheme: ${DARK.has(name) ? 'dark' : 'light'};\n}`;
};

const out = [
  '/* AUTO-GENERATED by scripts/generate-theme-css.mjs — do not edit by hand. */',
  '/* Source of truth: src/lib/theme/palettes.json */',
  '',
  block(':root', DEFAULT),
  '',
  ...Object.keys(palettes).map((name) => block(`[data-theme="${name}"]`, name)),
  '',
].join('\n');

writeFileSync('src/styles/themes.css', out);
console.log(`Wrote src/styles/themes.css (${Object.keys(palettes).length} aesthetics)`);
